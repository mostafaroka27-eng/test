def esc(s):
    s = html.escape(s, quote=False).replace("'", "\\'").replace('"','\\"')
    if s.startswith("@") or s.startswith("?"): s = "\\" + s
    return s
used = set(sys.argv[2].split())
for i, d in ((0, "values"), (1, "values-ar")):
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for k in sorted(S):
        extra = ' translatable="false"' if k.startswith("settings_language_") and k != "settings_language_system" and i == 0 else ''
        if i == 1 and extra: continue
        out.append(f'    <string name="{k}"{extra}>{esc(S[k][i])}</string>')
    for k in sorted(ARR):
        out.append(f'    <string-array name="{k}">')
        out += [f'        <item>{esc(x)}</item>' for x in ARR[k][i]]
        out.append('    </string-array>')
    out.append('</resources>')
    open(f"{sys.argv[1]}/{d}/strings.xml", "w").write("\n".join(out) + "\n")
