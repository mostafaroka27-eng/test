import {test, expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

const projectUpload = data => ({name:'project.json', mimeType:'application/json', buffer:Buffer.from(JSON.stringify(data))});

test('edits, undo/redo, autosave, exports, drawings and project roundtrip', async ({page}) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.locator('#addBase').click();
  await expect(page.locator('#tree button')).toHaveCount(2);
  await page.locator('#width').fill('1000');
  await page.locator('#width').press('Tab');
  await page.locator('#undo').click();
  await expect(page.locator('#width')).toHaveValue('800');
  await page.locator('#redo').click();
  await expect(page.locator('#width')).toHaveValue('1000');
  await page.locator('[data-bay="0"]').fill('0');
  await page.locator('[data-bay="0"]').press('Tab');
  await page.locator('[data-drawer="0"]').fill('2');
  await page.locator('[data-drawer="0"]').press('Tab');
  await expect(page.locator('#parts tr').filter({has:page.locator('td', {hasText:/^drawerFront$/})})).toHaveCount(2);
  await page.locator('#undo').click();
  await expect(page.locator('[data-drawer="0"]')).toHaveValue('0');
  await page.locator('#redo').click();
  await expect(page.locator('[data-drawer="0"]')).toHaveValue('2');
  await page.reload();
  await page.locator('#tree button').nth(1).click();
  await expect(page.locator('[data-bay="0"]')).toHaveValue('0');
  await expect(page.locator('[data-drawer="0"]')).toHaveValue('2');
  await page.locator('#parts tr').filter({has:page.locator('td', {hasText:/^drawerFront$/})}).first().click();
  await page.locator('[data-edge="0"]').uncheck();
  await page.reload();
  await expect(page.locator('#tree button')).toHaveCount(2);
  // Restored projects select their first cabinet; choose the edited cabinet.
  await page.locator('#tree button').nth(1).click();
  await expect(page.locator('#width')).toHaveValue('1000');
  await expect(page.locator('[data-drawer="0"]')).toHaveValue('2');
  const saved = page.waitForEvent('download');
  await page.locator('#save').click();
  const project = JSON.parse(await readFile(await (await saved).path(),'utf8'));
  expect(project.units[1].config.partOverrides['drawerFront:0'].edges[0]).toBe(0);
  await page.locator('#duplicate').click();
  await expect(page.locator('#tree button')).toHaveCount(3);
  page.once('dialog', dialog=>dialog.accept());
  await page.locator('#newProject').click();
  await expect(page.locator('#tree button')).toHaveCount(1);
  await page.locator('#file').setInputFiles(projectUpload(project));
  await expect(page.locator('#tree button')).toHaveCount(2);
  await page.locator('#tree button').nth(1).click();
  const csvDownload = page.waitForEvent('download');
  await page.locator('#projectCsv').click();
  const csv = await readFile(await (await csvDownload).path(),'utf8');
  expect(csv).toContain('drawerFront');
  await page.locator('[data-mode="drawings"]').click();
  await expect(page.locator('#drawingContent svg')).toBeVisible();
  await expect(page.locator('#drawingContent [data-view="front"] [data-kind="drawerFront"]')).toHaveCount(2);
  await expect(page.locator('#drawingContent [data-view="front"] [data-kind="shelf"]')).toHaveCount(0);
  const svgDownload = page.waitForEvent('download');
  await page.locator('#downloadSvg').click();
  expect(await readFile(await (await svgDownload).path(),'utf8')).toContain('PRELIMINARY');
  await page.locator('[data-mode="manufacturing"]').click();
  await expect(page.locator('#sheetInfo')).toContainText('sheets');
  await page.locator('[data-mode="render"]').click();
  const imageDownload = page.waitForEvent('download');
  await page.locator('#screenshot').click();
  expect((await readFile(await (await imageDownload).path())).subarray(0,8).toString('hex')).toBe('89504e470d0a1a0a');
  await page.locator('[data-mode="design"]').click();
  await page.locator('#present').click();
  await expect(page.locator('#presentationCanvas canvas')).toBeVisible();
  await page.locator('#closePresentation').click();
  await expect(page.locator('#viewport canvas')).toBeVisible();
  expect(errors).toEqual([]);
});

test('rejects malicious project atomically and opens legacy project files', async ({page}) => {
  await page.goto('/');
  const legacy = {format:'rokadex-standalone',version:1,units:[{id:'LEGACY-1',name:'Old cabinet',x:0,z:0,finish:'oak',config:{width:700}}]};
  await page.locator('#file').setInputFiles(projectUpload(legacy));
  await expect(page.locator('#width')).toHaveValue('700');
  const bad = structuredClone(legacy);
  bad.units[0].id='x" onclick="alert(1)';
  await page.locator('#file').setInputFiles(projectUpload(bad));
  await expect(page.locator('#projectStatus')).toContainText('Cannot open');
  await expect(page.locator('#width')).toHaveValue('700');
  await expect(page.locator('#tree button')).toHaveCount(1);
  await expect(page.locator('#tree button')).toHaveAttribute('data-id','LEGACY-1');
});

test('production build opens without external runtime dependencies and edits geometry', async ({page}) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {if(message.type()==='error')errors.push(message.text())});
  page.on('response', response => {if(response.status()>=400)errors.push(`${response.status()} ${response.url()}`)});
  await page.route('https://**/*', route => route.abort());
  await page.goto('/');
  await expect(page.locator('#viewport canvas')).toBeVisible();
  await expect(page.locator('#parts tr')).not.toHaveCount(0);
  await page.locator('#width').fill('1000');
  await page.locator('#width').press('Tab');
  await expect(page.locator('#parts tr').filter({has: page.locator('td', {hasText: /^top$/})}).locator('td').nth(2)).toHaveText('964');
  await page.reload();
  await expect(page.locator('#viewport canvas')).toBeVisible();
  expect(errors).toEqual([]);
});

test('Arabic labels preserve working inputs and persist language after refresh', async ({page}) => {
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.locator('#lang').click();
  await expect(page.locator('html')).toHaveAttribute('lang','ar');
  await expect(page.locator('html')).toHaveAttribute('dir','rtl');
  await expect(page.locator('#save')).toContainText('حفظ المشروع');
  await expect(page.locator('label').filter({has:page.locator('#width')})).toContainText('العرض');
  await page.locator('#width').fill('1100');
  await page.locator('#width').press('Tab');
  await expect(page.locator('#parts tr').filter({has: page.locator('td', {hasText: /^top$/})}).locator('td').nth(2)).toHaveText('1064');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang','ar');
  await expect(page.locator('#width')).toHaveValue('1100');
  await page.screenshot({path:'test-results/studio-arabic.png',fullPage:true});
  await page.locator('#lang').click();
  await expect(page.locator('html')).toHaveAttribute('lang','en');
  await expect(page.locator('#save')).toContainText('Save project');
  expect(errors).toEqual([]);
});
